def extract_metadata(target_dir):
    data_list = []
    # Mengambil daftar kategori
    categories = [c for c in os.listdir(target_dir) if os.path.isdir(os.path.join(target_dir, c))]

    for cat in categories:
        cat_path = os.path.join(target_dir, cat)
        for file in os.listdir(cat_path):
            file_path = os.path.join(cat_path, file)
            try:
                with Image.open(file_path) as img:
                    data_list.append({
                        'Nama_File': file,
                        'Kategori': cat,
                        'Format_Warna': img.mode,
                        'Lebar': img.size[0],
                        'Tinggi': img.size[1],
                        'Ukuran_KB': round(os.path.getsize(file_path) / 1024, 2)
                    })
            except:
                pass
    return pd.DataFrame(data_list)

