# Pembersihan File Rusak & Standarisasi Visual
for cat in categories:
    cat_path = os.path.join(working_dir, cat)
    for file in os.listdir(cat_path):
        f_path = os.path.join(cat_path, file)
        try:
            with Image.open(f_path) as img:
                img.verify()

            with Image.open(f_path) as img:
                clean_img = img.convert('RGB').resize((224, 224))
                clean_img.save(f_path)
            updated_files += 1
        except Exception:
            os.remove(f_path)
